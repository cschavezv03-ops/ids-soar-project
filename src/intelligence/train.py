"""
A4 - fit the three classifiers and persist their test-set predictions.

Scope. This module FITS models and WRITES their predictions to disk. It does
not choose a winner, does not plot anything and does not tune a decision
threshold: A5 compares, A6 sets the threshold. Every number reported here is
taken at the default 0.5 cut, which is a placeholder and not a decision - a
point worth remembering before quoting any of these figures as final.

It also does not preprocess. The split is read from data/processed/ exactly as
A3 left it (deduplicated, see contract/A3_preprocessing_note.md). If those
files are missing this module stops and says so rather than regenerating them:
silently rebuilding the dataset would make the numbers in the A3 report and the
numbers here refer to two different datasets.

The three models, and why each is here:

  1. Random Forest        the main model.
  2. Logistic regression  the comparison model: does a linear decision surface
                          suffice, or is the extra capacity actually used?
  3. Fixed-rule baseline  the question the whole project has to answer -
                          why machine learning instead of a threshold?

Usage (from the repo root):
    python src/intelligence/train.py
"""

