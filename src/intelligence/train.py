# The one invariant that no metric can check for us
# ---------------------------------------------------------------------------

def assert_contract_order(X) -> None:
    """Fail loudly unless the columns are exactly FEATURES_24, in order.

    Position IS the contract. A permuted frame trains a model that reads
    `flow_duration` out of the slot holding `tot_fwd_pkts`; every metric in
    this report would still look entirely plausible, and the live extractor -
    which emits the correct order - would then hand the model a vector it has
    never seen. No accuracy number can detect that, so it gets an assertion.

    Parquet stores columns in write order and nothing in the format obliges a
    reader to return them that way. `load_processed()` does select by name, so
    on the normal path this always passes; it is here for the day someone
    builds X some other way, which is exactly when it will matter.
    """
    got = list(getattr(X, "columns", []))
    if got != list(contract.FEATURES_24):
        raise AssertionError(
            "feature columns are not in contract order.\n"
            f"  expected: {list(contract.FEATURES_24)}\n"
            f"  got:      {got}"
        )


