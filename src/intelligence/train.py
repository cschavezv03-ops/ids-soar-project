def _class_balance_line(rep: Report, name: str, y) -> None:
    y = np.asarray(y)
    n = len(y)
    n_attack = int((y == contract.ATTACK).sum())
    n_benign = n - n_attack
    rep(f"    {name:<12} {n:>12,}   BENIGN {n_benign:>12,} ({n_benign / n:6.2%})"
        f"   ATTACK {n_attack:>11,} ({n_attack / n:6.2%})")


def main() -> int:
    ap = argparse.ArgumentParser(description="A4: fit the three classifiers.")
    ap.add_argument("--processed-dir", default=PROCESSED_DIR)
    ap.add_argument("--models-dir", default=MODELS_DIR)
    ap.add_argument("--report", default=REPORT_PATH)
    args = ap.parse_args()

    for name in ("train", "test"):
        path = os.path.join(args.processed_dir, f"{name}.parquet")
        if not os.path.exists(path):
            raise SystemExit(
                f"{path} not found. A4 does not regenerate the dataset - "
                f"rebuilding it here would silently decouple these numbers "
                f"from the ones in the A3 report. Run:\n"
                f"    python src/intelligence/preprocess.py --drop-duplicates"
            )

    rep = Report()
    rep("A4 training report - three classifiers on the CICIDS2017 split")
    rep(f"contract version {contract.CONTRACT_VERSION}   "
        f"random_state={RANDOM_STATE}")
    rep("Threshold is the sklearn default 0.5 throughout. That is a")
    rep("placeholder, not a decision: A6 sets the operating point.")

    # ---- data ----------------------------------------------------------
    rep.banner("1. DATA")
    X_train, X_test, y_train, y_test, label_train, label_test = load_processed(
        args.processed_dir
    )

    # Before anything is fitted. See assert_contract_order().
    assert_contract_order(X_train)
    assert_contract_order(X_test)
    rep(f"feature columns verified against contract.FEATURES_24: "
        f"{contract.N_FEATURES} columns, in order")
    rep("")
    rep(f"    {'set':<12} {'rows':>12}")
    _class_balance_line(rep, "train", y_train)
    _class_balance_line(rep, "test", y_test)
    rep("")
    rep("Matches contract/A3_preprocessing_note.md section 3 (deduplicated")
    rep("dataset, decision D3). Nothing was re-preprocessed here.")

    # ---- cross-validation ----------------------------------------------
    rep.banner("2. CROSS-VALIDATION (stability check)")
    X_cv, y_cv = stratified_subsample(
        X_train, y_train, label_train, CV_SUBSAMPLE, RANDOM_STATE
    )
    rep(f"{CV_FOLDS}-fold stratified CV, scoring = F1 of the attack class")
    rep(f"subsample: {len(X_cv):,} of {len(X_train):,} training rows "
        f"({len(X_cv) / len(X_train):.1%}), stratified on the family label")
    rep("")
    rep("This is a deliberate time trade-off, stated rather than hidden: the")
    rep("question CV answers is whether a score is stable across splits, and")
    rep("300k rows answer it as well as 1.6M for a fraction of the cost. The")
    rep("FINAL models below are fitted on the FULL training set.")
    rep("")

    builders = {
        RF_KEY: ("Random Forest", build_random_forest),
        LR_KEY: ("Logistic regression", build_logistic_regression),
        BASE_KEY: ("Fixed-rule baseline", build_baseline),
    }

    cv_results = {}
    rep(f"    {'model':<24} {'mean F1':>10} {'std':>10}   folds")
    for key, (title, build) in builders.items():
        scores = cross_validate_f1(build(), X_cv, y_cv)
        cv_results[key] = scores
        rep(f"    {title:<24} {scores.mean():>10.4f} {scores.std():>10.4f}   "
            + " ".join(f"{s:.4f}" for s in scores))

    # ---- fit on the full training set ----------------------------------
    rep.banner("3. FIT ON THE FULL TRAINING SET")

    fitted, fit_seconds, notes = {}, {}, {}
    for key, (title, build) in builders.items():
        model = build()
        start = time.perf_counter()
        if key == LR_KEY:
            # Convergence is a finding, not an assumption. Capture the warning
            # rather than let it scroll past in the terminal.
            with warnings.catch_warnings(record=True) as caught:
                warnings.simplefilter("always", ConvergenceWarning)
                model.fit(X_train, y_train)
            converged = not any(
                issubclass(w.category, ConvergenceWarning) for w in caught
            )
            n_iter = int(model.named_steps["logistic"].n_iter_[0])
            notes[key] = (
                f"converged in {n_iter} of {LOGREG_MAX_ITER} iterations"
                if converged else
                f"DID NOT CONVERGE in {LOGREG_MAX_ITER} iterations "
                f"(n_iter={n_iter}) - treat its coefficients with suspicion"
            )
        else:
            model.fit(X_train, y_train)
        fit_seconds[key] = time.perf_counter() - start
        fitted[key] = model
        rep(f"    {title:<24} fitted in {fit_seconds[key]:>8.1f} s")
        if key in notes:
            rep(f"    {'':<24} {notes[key]}")

    rule = fitted[BASE_KEY].named_steps["rule"]
    rep("")
    rep("Baseline threshold, chosen on TRAINING data only:")
    rep(f"    rule:            {rule.feature} {rule.direction_} "
        f"{rule.threshold_:,.6f} -> ATTACK")
    rep(f"    how:             swept {rule.n_candidates_} distinct candidate")
    rep("                     thresholds, taken as quantiles of the training")
    rep("                     values (observed values, never interpolated),")
    rep("                     in BOTH directions, keeping the best attack F1")
    rep(f"    its train F1:    {rule.train_f1_:.4f}")
    rep("")
    rep("    Both directions, on training data:")
    for direction in (">=", "<="):
        score = rule.direction_scores_[direction]
        marker = "  <- kept" if direction == rule.direction_ else ""
        rep(f"        {rule.feature} {direction} {score['threshold']:>12.6f}"
            f"   F1 = {score['f1']:.4f}{marker}")
    constant_f1 = 2 * int((np.asarray(y_train) == contract.ATTACK).sum()) / (
        len(y_train) + int((np.asarray(y_train) == contract.ATTACK).sum())
    )
    rep(f"        (a classifier that flags EVERY flow scores {constant_f1:.4f})")
    rep("")
    rep("    The operational rule is worded 'more than N connections in 10")
    rep("    seconds', i.e. HIGH rate = attack. On this data that direction is")
    rep("    worth essentially nothing: it scores what a constant 'everything")
    rep("    is an attack' classifier scores. Median flow_pkts_s is 0.19 for")
    rep("    attacks and 54.42 for benign traffic - the dataset's attacks are")
    rep("    the SLOW flows, because a DoS holds connections open and a scan")
    rep("    probe is one packet in a flow that then waits. The direction is")
    rep("    therefore fitted on TRAINING data like the threshold, so that the")
    rep("    comparison in A5 is against the rule at its best and not against")
    rep("    a strawman of our own wording.")

    # ---- predict and score ---------------------------------------------
    rep.banner("4. ATTACK-CLASS SCORES ON TEST (threshold 0.5)")

    predictions, scores_test = {}, {}
    for key, (title, _) in builders.items():
        y_pred = fitted[key].predict(X_test)
        predictions[f"{key}_pred"] = np.asarray(y_pred, dtype=np.int8)
        scores_test[key] = attack_scores(y_test, y_pred)
        if hasattr(fitted[key], "predict_proba"):
            predictions[f"{key}_proba"] = fitted[key].predict_proba(X_test)[:, 1]

    rep(f"    {'model':<24} {'precision':>10} {'recall':>10} {'F1':>10}")
    for key, (title, _) in builders.items():
        s = scores_test[key]
        rep(f"    {title:<24} {s['precision']:>10.4f} {s['recall']:>10.4f} "
            f"{s['f1']:>10.4f}")
    rep("")
    rep("The baseline has no probability output by construction, so it has no")
    rep("ROC curve and no AUC. A5 must compare it on these three numbers only.")

    # ---- overfitting check ---------------------------------------------
    rep.banner("5. RANDOM FOREST: TRAIN vs TEST (overfitting check)")
    rf_train = attack_scores(y_train, fitted[RF_KEY].predict(X_train))
    rf_test = scores_test[RF_KEY]
    rep(f"    {'':<12} {'precision':>10} {'recall':>10} {'F1':>10}")
    rep(f"    {'TRAIN':<12} {rf_train['precision']:>10.4f} "
        f"{rf_train['recall']:>10.4f} {rf_train['f1']:>10.4f}")
    rep(f"    {'TEST':<12} {rf_test['precision']:>10.4f} "
        f"{rf_test['recall']:>10.4f} {rf_test['f1']:>10.4f}")
    rep(f"    {'gap':<12} {'':>10} {'':>10} "
        f"{rf_train['f1'] - rf_test['f1']:>10.4f}")
    rep("")
    rep("A forest with max_depth=None fits the training set almost perfectly by")
    rep("construction, so a gap here is expected and is not by itself evidence")
    rep("of a broken model. What matters is the size of the TEST number.")

    # ---- per-family recall ---------------------------------------------
    rep.banner("6. RECALL PER ATTACK FAMILY ON TEST")
    rep("The argument for machine learning over a fixed rule lives or dies")
    rep("here. Measured, not assumed.")
    rep("")
    tables = {k: per_family_recall(label_test, y_test, predictions[f"{k}_pred"])
              for k in builders}
    reference = tables[RF_KEY]
    rep(f"    {'family':<20} {'metric':<20} {'n':>9} "
        + "".join(f"{builders[k][0].split()[0]:>12}" for k in builders))
    for _, row in reference.iterrows():
        cells = ""
        for key in builders:
            table = tables[key]
            value = table.loc[table["family"] == row["family"], "value"].iloc[0]
            cells += f"{value:>12.4f}"
        rep(f"    {row['family']:<20} {row['metric']:<20} {row['n']:>9,}{cells}")

    # ---- persist --------------------------------------------------------
    rep.banner("7. PERSISTED")
    extra = {
        BASE_KEY: {"threshold": rule.threshold_, "feature": rule.feature,
                   "direction": rule.direction_},
    }
    for key, (title, _) in builders.items():
        path = MODEL_FILES[key] if args.models_dir == MODELS_DIR else os.path.join(
            args.models_dir, os.path.basename(MODEL_FILES[key])
        )
        persist_model(path, title, fitted[key],
                      cv_mean_f1=float(cv_results[key].mean()),
                      cv_std_f1=float(cv_results[key].std()),
                      fit_seconds=fit_seconds[key],
                      n_train_rows=len(X_train),
                      **extra.get(key, {}))
        rep(f"    {path:<44} contract {contract.CONTRACT_VERSION}")

    persist_predictions(PREDICTIONS_PATH, y_test, label_test, predictions)
    rep(f"    {PREDICTIONS_PATH:<44} {len(y_test):,} rows, "
        f"{len(predictions)} prediction columns + y_true + {LABEL_COL}")
    rep("")
    rep("Both models/*.joblib and data/ are gitignored. The reproducible")
    rep("artifact is this script plus the note, not the bytes on disk.")

    rep.banner("DONE")
    rep("Three models fitted. No winner chosen, no threshold tuned, nothing")
    rep("plotted - that is A5 and A6.")

    rep.save(args.report)
    print(f"\nreport saved to {args.report}")
    return 0


