# Model 3 - the fixed-rule baseline
# ---------------------------------------------------------------------------

class FixedRuleBaseline(BaseEstimator, ClassifierMixin):
    """The threshold rule that machine learning has to beat.

    WHY IT IS NOT "more than N connections in 10 seconds". The master document
    words the baseline that way, and that rule cannot be implemented in this
    component. Saying so precisely matters more than approximating it: the rule
    needs a per-source-IP counter with memory across flows, and this component
    is handed one finished flow at a time, with no IP (identity features are
    excluded from the contract as data leakage - A1 section 6.3) and no state
    between calls. That counter does exist in the system: it is the SOAR
    correlation that groups flows by source IP into one case. But it lives in
    component B, it is not a classifier, and it is not what A5 is comparing.

    THE HONEST TRANSLATION. One feature, one threshold: `flow_pkts_s`
    (position 21). Packets per second is the per-flow shadow of "connections
    per second" - the same intuition, measured on the only thing we can see.

    THE DIRECTION IS FITTED, NOT ASSUMED - and this was a finding, not a
    preference. The operational rule implies "high rate means attack", so that
    is the direction this class was first written with. Measured on the
    training set, that direction is worth F1 = 0.2861, while a classifier that
    labels EVERY flow an attack scores 0.2857: the rule as worded carries
    essentially no information on this data. The reason is visible in one
    line - median `flow_pkts_s` is 0.19 for attacks and 54.42 for benign
    traffic. The dataset's attacks are the SLOW flows, because a DoS holds
    connections open and a scan probe is one packet in a flow that then waits.

    So `fit` sweeps BOTH directions and keeps whichever scores better ON THE
    TRAINING SET, and the report prints both numbers. This is not the baseline
    being given the answer: no test row is involved, the rule still sees one
    feature, and a comparison against a strawman would prove nothing about
    machine learning. Reporting that the fixed rule is worthless because we
    aimed it backwards would be an artefact of our own wording, not a finding.

    NO predict_proba, DELIBERATELY. A threshold rule has no notion of
    confidence, therefore no ROC curve and no AUC. Manufacturing one by
    rescaling the feature would fabricate a curve the rule does not possess and
    would flatter it against models that genuinely produce one. A5 compares it
    on precision, recall and F1 alone.
    """

    def __init__(self, feature: str = "flow_pkts_s", n_candidates: int = 400):
        self.feature = feature
        self.n_candidates = n_candidates

    def _column(self, X) -> np.ndarray:
        """The one feature this rule looks at, from a frame or a raw array."""
        if hasattr(X, "columns"):
            return np.asarray(X[self.feature], dtype=np.float64)
        return np.asarray(X, dtype=np.float64)[
            :, contract.FEATURES_24.index(self.feature)
        ]

    def fit(self, X, y):
        """Pick the threshold that maximises attack-class F1 ON TRAINING DATA.

        Calibrating the cut on the test set would hand the baseline an
        advantage the other two models are not given, and the comparison A5
        makes would be worthless. The grid is quantiles of the training values,
        so the candidates follow the data's own distribution instead of an
        arbitrary linear range over a feature whose scale spans decades.
        """
        values = self._column(X)
        target = np.asarray(y)
        positive = target == contract.ATTACK
        n_positive = int(positive.sum())

        quantiles = np.linspace(0.0, 1.0, self.n_candidates)
        # method="lower" keeps every candidate an OBSERVED value. With a
        # `>=` rule the best threshold always coincides with one of the
        # observed values, so interpolating between them can only land in a
        # gap between two populations and miss the optimum that sits at the
        # edge of it - which is exactly the shape this data has.
        candidates = np.unique(np.quantile(values, quantiles, method="lower"))

        best = {"direction": ">=", "threshold": float(candidates[0]), "f1": -1.0}
        per_direction = {}

        for direction in (">=", "<="):
            direction_best = {"threshold": float(candidates[0]), "f1": -1.0}
            for threshold in candidates:
                predicted = (values >= threshold if direction == ">="
                             else values <= threshold)
                true_positive = int(np.count_nonzero(predicted & positive))
                n_predicted = int(np.count_nonzero(predicted))
                # F1 straight from the counts: 400 sweeps over 1.6M rows
                # through sklearn's f1_score would spend most of the time in
                # input validation.
                denominator = n_predicted + n_positive
                f1 = (2.0 * true_positive / denominator) if denominator else 0.0
                if f1 > direction_best["f1"]:
                    direction_best = {"threshold": float(threshold), "f1": f1}
            per_direction[direction] = direction_best
            if direction_best["f1"] > best["f1"]:
                best = {"direction": direction, **direction_best}

        self.classes_ = np.array([contract.BENIGN, contract.ATTACK])
        self.direction_ = best["direction"]
        self.threshold_ = float(best["threshold"])
        self.train_f1_ = float(best["f1"])
        # Kept so the report can show what the rule AS WORDED was worth, next
        # to what it is worth aimed the way the data actually points.
        self.direction_scores_ = per_direction
        self.n_candidates_ = int(len(candidates))
        self.n_features_in_ = X.shape[1]
        return self

    def predict(self, X) -> np.ndarray:
        check_is_fitted(self, "threshold_")
        values = self._column(X)
        flagged = (values >= self.threshold_ if self.direction_ == ">="
                   else values <= self.threshold_)
        return flagged.astype(np.int8)


