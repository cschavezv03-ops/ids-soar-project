def build_random_forest() -> Pipeline:
    """Estimator only, no scaler - and that is a decision, not an omission.

    A decision tree splits on the ORDER of a feature's values, never on their
    magnitude, so any monotone rescaling produces the identical tree. A
    StandardScaler here would cost a full pass over 1.6M rows to change
    nothing, and would add a fitted component that can go stale.

    Hyperparameters stay at sklearn's defaults on purpose: A4 is not a tuning
    task, and a tuned forest compared against an untuned baseline would not be
    the comparison A5 is asked to make.
    """
    return Pipeline([
        ("forest", RandomForestClassifier(
            # The imbalance treatment decided in A1 and deferred by A3 to here:
            # it is a model hyperparameter, so it belongs in the model, not in
            # a resampled copy of the training data.
            class_weight="balanced",
            random_state=RANDOM_STATE,
            n_jobs=-1,
        )),
    ])


def build_logistic_regression() -> Pipeline:
    """StandardScaler THEN LogisticRegression, both inside one Pipeline.

    Logistic regression is not scale-invariant: `flow_duration` reaches 1.2e8
    microseconds while `fwd_act_data_pkts` is a count in the single digits, and
    lbfgs on columns of that spread converges slowly and badly. So it needs the
    scaler. The question is where the scaler lives, and the answer is INSIDE
    the Pipeline, never fitted outside it, for two independent reasons:

    1. CROSS-VALIDATION. A scaler fitted on the whole training set before the
       folds are cut has already seen the rows it is about to be validated on:
       their mean and variance are baked into the transform, and the CV score
       comes back optimistic. Inside a Pipeline, sklearn refits the scaler on
       each training fold only, which is the sole correct order.

    2. SERIALISATION. joblib.dump on a bare estimator saves the coefficients
       and NOT the scaler. The model then loads without complaint and predicts
       with total confidence on unscaled live vectors - a silent failure, which
       is the class of failure this project documents as critical. A Pipeline
       is one object and cannot be separated from its own preprocessing.
    """
    return Pipeline([
        ("scaler", StandardScaler()),
        ("logistic", LogisticRegression(
            class_weight="balanced",
            random_state=RANDOM_STATE,
            max_iter=LOGREG_MAX_ITER,
        )),
    ])


def build_baseline() -> Pipeline:
    """Wrapped in a Pipeline so it goes through the identical evaluation code.

    Nothing to preprocess - a threshold on one raw feature is the whole model.
    The wrapper exists so that A5 cannot accidentally treat the baseline as a
    special case and evaluate it differently from the models it is judging.
    """
    return Pipeline([("rule", FixedRuleBaseline())])


