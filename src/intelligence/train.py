def persist_model(path: str, name: str, pipeline: Pipeline, **extra) -> None:
    """Save the fitted Pipeline together with the contract it was trained on.

    The version travels WITH the model, in the same file, because the failure
    it prevents is a model built against one feature order being loaded by code
    that assumes another. Two files that must be kept in step would eventually
    fall out of step; one file cannot.
    """
    os.makedirs(os.path.dirname(path), exist_ok=True)
    joblib.dump({
        "name": name,
        "contract_version": contract.CONTRACT_VERSION,
        "features": list(contract.FEATURES_24),
        "pipeline": pipeline,
        "random_state": RANDOM_STATE,
        "trained_at": time.strftime("%Y-%m-%d %H:%M:%S"),
        **extra,
    }, path)


def load_model(path: str) -> dict:
    """Load a model and refuse it if it does not match the current contract."""
    payload = joblib.load(path)
    if payload["contract_version"] != contract.CONTRACT_VERSION:
        raise ValueError(
            f"{path} was trained against contract "
            f"{payload['contract_version']}, this code is "
            f"{contract.CONTRACT_VERSION}. Retrain; do not override."
        )
    if payload["features"] != list(contract.FEATURES_24):
        raise ValueError(f"{path} was trained on a different feature order.")
    return payload


def persist_predictions(path: str, y_test, label_test, predictions: dict) -> None:
    """Write the test-set predictions so A5 never has to refit anything.

    A5 is a comparison task; it should read numbers, not spend twenty minutes
    reproducing them and risk reproducing them slightly differently.
    """
    os.makedirs(os.path.dirname(path), exist_ok=True)
    frame = pd.DataFrame({
        "y_true": np.asarray(y_test),
        LABEL_COL: np.asarray(label_test),
    })
    for key, values in predictions.items():
        frame[key] = values
    frame.to_parquet(path, index=False)


def load_predictions(path: str = PREDICTIONS_PATH) -> pd.DataFrame:
    """Read back what persist_predictions wrote. For A5."""
    return pd.read_parquet(path)


