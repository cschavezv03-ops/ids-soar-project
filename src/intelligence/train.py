# Evaluation helpers - measurement only, no comparison
# ---------------------------------------------------------------------------

def attack_scores(y_true, y_pred) -> dict:
    """Precision, recall and F1 of the ATTACK class. The benign class is the
    easy 83%; reporting its scores would flatter every model equally."""
    precision, recall, f1, _ = precision_recall_fscore_support(
        y_true, y_pred, labels=[contract.ATTACK], zero_division=0
    )
    return {"precision": float(precision[0]),
            "recall": float(recall[0]),
            "f1": float(f1[0])}


def per_family_recall(labels, y_true, y_pred) -> pd.DataFrame:
    """Recall for each attack family, plus the benign false-positive rate.

    Recall is undefined for BENIGN in an attack-class framing, so that row
    reports the rate at which benign flows are called attacks instead. Both
    matter to the defence: a rule that catches everything by alarming on
    everything is not a detector.
    """
    frame = pd.DataFrame({"label": np.asarray(labels),
                          "y_true": np.asarray(y_true),
                          "y_pred": np.asarray(y_pred)})
    rows = []
    for name, group in frame.groupby("label", sort=False):
        flagged = float((group["y_pred"] == contract.ATTACK).mean())
        is_benign = group["y_true"].iloc[0] == contract.BENIGN
        rows.append({
            "family": name,
            "n": len(group),
            "metric": "false positive rate" if is_benign else "recall",
            "value": flagged,
        })
    return pd.DataFrame(rows).sort_values(
        ["metric", "n"], ascending=[True, False]
    ).reset_index(drop=True)


def stratified_subsample(X, y, labels, n: int, random_state: int):
    """A representative slice for the CV stability check.

    Stratified on the FAMILY string, not the binary target, for the same reason
    A3 split that way: PortScan is 0.10% of the data after deduplication, and a
    subsample stratified only on benign/attack could leave a fold with almost
    none of it.
    """
    if n >= len(X):
        return X, y
    X_sub, _, y_sub, _ = train_test_split(
        X, y, train_size=n, stratify=labels, random_state=random_state
    )
    return X_sub, y_sub


def cross_validate_f1(model, X, y) -> np.ndarray:
    """5-fold stratified CV on attack-class F1.

    n_jobs=1 on the outer loop: the forest already parallelises across all
    cores internally, and nesting the two oversubscribes them.
    """
    folds = StratifiedKFold(n_splits=CV_FOLDS, shuffle=True,
                            random_state=RANDOM_STATE)
    return cross_val_score(model, X, y, cv=folds, scoring="f1", n_jobs=1)


